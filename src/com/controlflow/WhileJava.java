package com.controlflow;

public class WhileJava {

	public static void main(String[] args) {
		
		//controlla la condizione prima di eseguire il codice, se la condizione è falsa, il blocco non viene mai eseguito
		
		
		
		int countdown = 10;

		while (countdown > 0) {
		  System.out.println(countdown);
		  countdown--;
		}

		System.out.println("Happy New Year!!");
		
		
		
		int i = 1;
		
		while (i<= 5) {
		System.out.println("contatore" + i);
		i++;
	}

  }
}
