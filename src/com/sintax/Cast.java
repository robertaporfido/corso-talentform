package com.sintax;

public class Cast {

	public static void main(String[] args) {
		
		// CAST IMPLICIT
		int number= 3;
		float numbers = number;
		System.out.println(numbers);
		
		// CAST EXPLICIT
		double d1 = 100;
		float f1 = (float) d1;
		System.out.println(f1);
		
		
		int x = 250;
		float y = x;
		System.out.println(y);
		
		double r = 25.5;
		int q = (int) r;
		System.out.println(q);
		
		// SISTEMA ESPLICITO A DUE FATTORI
		double w = 27.9;
		float g = (float) w;
		int j = (int) g;
	
		System.out.println(j);
		
		
		
		
			
		

	}

}
